// Generate themes/icons/apple-map.js from apple-map.txt (the one mapping Linux app -> macOS icon).
// Usage: node themes/icons/tools/gen-map.mjs [--check]     (--check fails when apple-map.js is stale)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const icons = join(dirname(fileURLToPath(import.meta.url)), "..");
const norm = s => String(s || "").toLowerCase().replace(/\.desktop$/, "");
const seg = s => norm(s).split(".").pop();

const exact = {}, bySegment = {};
const problems = [];
for (const [i, raw] of readFileSync(join(icons, "apple-map.txt"), "utf8").split("\n").entries()) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const parts = line.split(/\s+/);
    if (parts.length !== 2) { problems.push(`apple-map.txt:${i + 1}: need "<name> <Apple name>"`); continue; }
    const [name, mac] = parts;
    const dir = mac.startsWith("@") ? "system" : "apps";
    if (!existsSync(join(icons, dir, `${mac.replace(/^@/, "")}-512.png`)))
        problems.push(`apple-map.txt:${i + 1}: ${dir}/${mac.replace(/^@/, "")}-512.png does not exist`);
    const k = norm(name);
    if (exact[k] && exact[k] !== mac) problems.push(`apple-map.txt:${i + 1}: ${name} already maps to ${exact[k]}`);
    exact[k] ??= mac;
    bySegment[seg(name)] ??= mac;
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

const pretty = o => "{\n" + Object.entries(o).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n") + "\n}";
const out = `.pragma library
// GENERATED by themes/icons/tools/gen-map.mjs from apple-map.txt. Do not edit.
// Linux app id / icon name -> macOS icon name (themes/icons/apps/<Name>-512.png, or
// themes/icons/system/<Name>-512.png when the name starts with "@").
// shell/services/macicons.js and finder/qml/lib/macicons.js are symlinks to this file.

const exact = ${pretty(exact)};
const bySegment = ${pretty(bySegment)};

function norm(s) {
    return String(s || "").toLowerCase().replace(/\\.desktop$/, "");
}

// Mapped macOS icon for the first name that has one (desktop id, Icon= name, window class...),
// "" when none does. The whole name wins over its last dot segment.
function lookup(names) {
    const list = Array.isArray(names) ? names : [names];
    for (const n of list) {
        const k = norm(n);
        if (k && exact[k]) return exact[k];
    }
    for (const n of list) {
        const k = norm(n).split(".").pop();
        if (k && bySegment[k]) return bySegment[k];
    }
    return "";
}

// File of a mapped icon relative to themes/icons, e.g. "apps/Safari-512.png"
function file(mac, px) {
    return mac ? (mac[0] === "@" ? "system/" + mac.slice(1) : "apps/" + mac) + "-" + (px || 512) + ".png" : "";
}
`;
const target = join(icons, "apple-map.js");
if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== out) { console.error("apple-map.js is stale: run node themes/icons/tools/gen-map.mjs"); process.exit(1); }
} else writeFileSync(target, out);
console.log(`apple-map: ${Object.keys(exact).length} names, ${Object.keys(bySegment).length} segments`);
