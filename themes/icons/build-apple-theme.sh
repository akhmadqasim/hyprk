#!/usr/bin/env bash
# Build the LOCAL "hyprk-apple" icon theme layer: the user's extracted macOS app icons
# (themes/icons/apps, untracked, see reference/ASSETS.md) under Linux icon names from
# apple-map.txt, inheriting WhiteSur (themes/icons/install.sh) and then the system theme.
# Output: themes/icons/hyprk-apple/ (untracked, symlinks into ../apps). Nothing is built when
# the Apple icons are missing, so a fresh checkout keeps WhiteSur + squircle tiles.
# Usage: themes/icons/build-apple-theme.sh [--remove]
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
out=$here/hyprk-apple
rm -rf "$out"
[ "${1:-}" = --remove ] && { echo "removed $out"; exit 0; }
ls "$here"/apps/*-512.png >/dev/null 2>&1 || { echo "no macOS icons in $here/apps, nothing to build"; exit 0; }

sys=$(gsettings get org.gnome.desktop.interface icon-theme 2>/dev/null | tr -d "'" || true)
inherits=WhiteSur
[ -n "$sys" ] && [ "$sys" != WhiteSur ] && inherits="$inherits,$sys"
inherits="$inherits,Adwaita,hicolor"

mkdir -p "$out/512x512/apps" "$out/128x128/apps"
n=0
while read -r name mac; do
    case $name in ''|'#'*) continue ;; esac
    for s in 512 128; do
        [ -f "$here/apps/$mac-$s.png" ] && ln -sf "../../../apps/$mac-$s.png" "$out/${s}x$s/apps/$name.png"
    done
    n=$((n + 1))
done < "$here/apple-map.txt"
cat > "$out/index.theme" <<EOT
[Icon Theme]
Name=hyprk-apple
Comment=Local macOS app icons (not redistributable), generated by build-apple-theme.sh
Inherits=$inherits
Directories=512x512/apps,128x128/apps

[512x512/apps]
Size=512
MinSize=129
MaxSize=1024
Context=Applications
Type=Scalable

[128x128/apps]
Size=128
MinSize=16
MaxSize=128
Context=Applications
Type=Scalable
EOT
echo "hyprk-apple: $n names -> $out (Inherits=$inherits)"
